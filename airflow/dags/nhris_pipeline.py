from datetime import datetime
from airflow import DAG
from airflow.operators.python import PythonOperator
from airflow.operators.bash import BashOperator
import sys
from pathlib import Path
import os

ROOT = Path("/opt")
DATA_GEN = ROOT / "spark-apps" / "data_generator" / "generate_data.py"
SPARK_JOB = ROOT / "spark-apps" / "jobs" / "process_health_data.py"


def run_generator():
    os.environ["NHRIS_DATA"] = "/opt/data"
    sys.path.append(str(DATA_GEN.parent))
    from generate_data import main
    main(rows=500)


with DAG(
    dag_id="nhris_pipeline",
    start_date=datetime(2026, 1, 1),
    schedule_interval="@hourly",
    catchup=False,
    tags=["nhris", "health"],
) as dag:
    ingest_data = PythonOperator(
        task_id="ingest_data",
        python_callable=run_generator,
    )

    process_with_spark = BashOperator(
        task_id="process_with_spark",
        bash_command=(
            "NHRIS_DATA=/opt/data NHRIS_DELTA=/opt/delta "
            "spark-submit --master spark://spark-master:7077 "
            "--packages io.delta:delta-spark_2.12:3.2.0 "
            "/opt/spark-apps/jobs/process_health_data.py"
        ),
    )

    generate_alerts = BashOperator(
        task_id="generate_alerts",
        bash_command="echo 'Alerts generated by Spark job.'",
    )

    ingest_data >> process_with_spark >> generate_alerts
